def link(from_label, to_label, rtype):
    a=find([from_label]); b=find([to_label])
    if not a or not b:
        # print('link skip', from_label, to_label);
        return
    data['links'].append({'from':a['id'],'to':b['id'],'type':rtype,'dir':'directed'})

